package fr.hesias.dmd.infrastructure.persistence.oracle;

import fr.hesias.dmd.domain.model.PlaceType;
import fr.hesias.dmd.domain.model.Report;
import org.junit.jupiter.api.Test;
import org.springframework.test.util.ReflectionTestUtils;

import java.time.Instant;

import static org.junit.jupiter.api.Assertions.*;

class OracleReportEntityTest {

    private static final Instant TIMESTAMP =
            Instant.parse("2026-11-22T12:00:00Z");

    private static Report createReport() {
        return new Report(
                null,
                48.8566,
                2.3522,
                PlaceType.PARK,
                2,
                TIMESTAMP
        );
    }

    @Test
    void shouldPreserveReportDataDuringMapping() {
        Report original = createReport();

        OracleReportEntity entity =
                new OracleReportEntity(original);

        assertEquals(original, entity.toDomain());
    }

    @Test
    void shouldPreserveGeneratedIdAndTimestamp() {
        OracleReportEntity entity =
                new OracleReportEntity(createReport());

        // Simulate an identifier generated by Oracle.
        ReflectionTestUtils.setField(entity, "id", 42L);

        Report restored = entity.toDomain();

        assertAll(
                () -> assertEquals(42L, restored.id()),
                () -> assertEquals(TIMESTAMP, restored.timestamp()),
                () -> assertEquals(PlaceType.PARK, restored.placeType()),
                () -> assertEquals(2, restored.crowdLevel())
        );
    }
}
